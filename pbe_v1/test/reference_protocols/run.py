"""Generate independent-library USB/Modbus packets and run them through PBE pins."""
from __future__ import annotations
import argparse
import hashlib
import importlib.metadata
import json
import os
from pathlib import Path
import random
import re
import shutil
import subprocess
import sys
import time

ROOT = Path(__file__).resolve().parents[2]
SOURCES = [ROOT/'src'/f'{name}.sv' for name in
           ('pbe_fifo','pbe_host_spi','pbe_crc','pbe_line','pbe_engine','tt_um_pbe')]


def queue(data):
    return "'{" + ', '.join(f"8'h{n:02x}" for n in data) + '}'


def packet_bytes(bits):
    assert len(bits) % 8 == 0
    return bytes(int(bits[i:i+8][::-1], 2) for i in range(0,len(bits),8))


def usb_vectors(output, rng):
    # All PID, token CRC5, data CRC16 and packet bit encodings are external.
    # The adapter below only converts their LSB-first bits to SV byte literals.
    from luna.gateware.test.contrib import usb_packet as up
    from usb_protocol.types import USBPacketID
    entries, labels = [], {}

    def add(label, bits):
        raw = packet_bytes(bits)
        labels[label] = len(entries)
        entries.append({'label':label, 'hex':raw.hex(), 'bits':bits})
        # Independent GSG PID parser also checks the complemented nibble.
        assert not USBPacketID.from_int(raw[0],skip_checks=False).is_invalid()
        return labels[label]

    for label, pid, addr in [('setup',up.PID.SETUP,0),('in',up.PID.IN,0),
                              ('out',up.PID.OUT,0),('wrong_address',up.PID.IN,37)]:
        add(label,up.token_packet(pid,addr,0))
    bad = list(entries[labels['in']]['bits']);bad[-1] = str(1-int(bad[-1]))
    add('bad_crc5',''.join(bad))
    for name in ('ACK','NAK','STALL'):
        add(name.lower(),up.handshake_packet(getattr(up.PID,name)))
    descriptor = bytes.fromhex('12 01 10 01 ff 00 00 08 34 12 78 56 00 01 00 00 00 01')
    payload = bytes([0xff,0xff]+[rng.randrange(256) for _ in range(5)])
    setups = {
        'get_descriptor':bytes.fromhex('80 06 00 01 00 00 12 00'),
        'vendor_write':bytes.fromhex('40 01 00 00 00 00 07 00'),
        'vendor_read':bytes.fromhex('c0 02 00 00 00 00 08 00'),
        'unsupported':bytes.fromhex('80 06 02 03 09 04 40 00')}
    for label,data in setups.items():add(label,up.data_packet(up.PID.DATA0,data))
    corrupt = list(entries[labels['get_descriptor']]['bits']);corrupt[-1]=str(1-int(corrupt[-1]))
    add('bad_crc16',''.join(corrupt))
    add('descriptor0',up.data_packet(up.PID.DATA1,descriptor[:8]))
    add('descriptor1',up.data_packet(up.PID.DATA0,descriptor[8:16]))
    add('descriptor2',up.data_packet(up.PID.DATA1,descriptor[16:]))
    add('empty_data1',up.data_packet(up.PID.DATA1,[]))
    add('vendor_payload',up.data_packet(up.PID.DATA1,payload))
    add('vendor_reply',up.data_packet(up.PID.DATA1,payload[::-1]+b'\x55'))
    lines = ['// Generated by pinned external packet libraries; do not edit.',
             'logic [7:0] usb_ref_expected[$];',
             'task automatic usb_ref_bytes(input int index);', '  case(index)']
    for index, entry in enumerate(entries):
        lines.append(f'    {index}: h_pkt = {queue(bytes.fromhex(entry["hex"]))}; // {entry["label"]}')
    lines += ['    default: $fatal(1,"unknown independent USB packet");',
              '  endcase','endtask',
              'task automatic usb_ref_send(input int index);',
              '  usb_ref_bytes(index);',
              '  $write("REF_USB_SENT %0d ",index); foreach(h_pkt[i]) $write("%02x",h_pkt[i]); $display("");',
              '  hs_send;', 'endtask',
              'task automatic usb_ref_expect(input int index);',
              '  usb_ref_bytes(index); usb_ref_expected = h_pkt;',
              '  check(r_ok, "independent USB expected device response");',
              '  check(r_pkt.size() == usb_ref_expected.size(), $sformatf("independent USB response size %0d expected %0d",r_pkt.size(),usb_ref_expected.size()));',
              '  foreach(usb_ref_expected[i]) if(i < r_pkt.size())',
              '    check(r_pkt[i] === usb_ref_expected[i], $sformatf("independent USB response byte %0d got %02x expected %02x",i,r_pkt[i],usb_ref_expected[i]));',
              '  $write("REF_USB_RESPONSE %0d ",index); foreach(r_pkt[i]) $write("%02x",r_pkt[i]); $display("");',
              'endtask',
              'task automatic usb_ref_in(input int expected);',
              '  int tries;', '  tries=0;',
              f'  do begin usb_ref_send({labels["in"]}); hs_recv; tries++;',
              "    if(r_ok && r_pkt.size()==1 && r_pkt[0]==8'h5a) repeat(400) @(posedge clk);",
              "  end while(r_ok && r_pkt.size()==1 && r_pkt[0]==8'h5a && tries<200);",
              '  usb_ref_expect(expected);','endtask',
              'task automatic usb_reference;',
              '  $display("Independent USB packet-library pin tests");',
              '  h_pct=0;']
    expected_responses=[]
    def send(label):lines.append(f'  usb_ref_send({labels[label]});')
    def expect(label):
        expected_responses.append(labels[label])
        lines.append(f'  hs_recv; usb_ref_expect({labels[label]}); gap;')
    def receive_in(label):
        expected_responses.append(labels[label])
        lines.append(f'  usb_ref_in({labels[label]});')
    def setup(label):
        send('setup');send(label);expect('ack')
    for label in ('wrong_address','bad_crc5'):
        send(label);lines.append('  hs_recv; check(!r_ok,"independent USB invalid/address token was answered"); gap;')
    send('setup');send('bad_crc16');lines += ['  hs_recv; check(!r_ok,"independent USB bad CRC16 was ACKed"); gap;',
                                                            '  repeat(5000) @(posedge clk);']
    setup('get_descriptor')
    for label in ('descriptor0','descriptor1','descriptor2'):
        receive_in(label);send('ack');lines.append('  gap;')
    send('out');send('empty_data1');expect('ack')
    setup('vendor_write');send('out');send('vendor_payload');expect('ack')
    receive_in('empty_data1');send('ack');lines.append('  gap;')
    setup('vendor_read');receive_in('vendor_reply');send('ack');lines.append('  gap;')
    send('out');send('empty_data1');expect('ack')
    setup('unsupported');receive_in('stall');lines.append('  gap;')
    lines += ['  repeat(6000) @(posedge clk); fw_run=0;',
              '  check(contention==0,"independent USB bus contention");',
              '  check(r_bad==0,"independent USB response stuffing errors");',
              '  check(fw_bad==1,"independent USB corrupt DATA record count");',
              '  check(tt_min>=2.0 && tt_max<=7.5,"independent USB turnaround outside USB bounds");',
              '  if(errors) $fatal(1,"independent USB vectors failed: %0d",errors);',
              '  $display("REFERENCE_USB_PASS packets=%0d turnaround=%0.3f..%0.3f",'+str(len(entries))+',tt_min,tt_max);',
              'endtask']
    (output/'usb_reference.svh').write_text('\n'.join(lines)+'\n')
    return {'packets':entries,'vendor_payload':payload.hex(),'labels':labels,
            'expected_responses':expected_responses}


def modbus_vectors(output,rng):
    from pymodbus.framer.rtu import FramerRTU
    from pymodbus.pdu import DecodePDU
    from pymodbus.pdu.register_message import ReadHoldingRegistersRequest, ReadHoldingRegistersResponse
    req_framer,resp_framer=FramerRTU(DecodePDU(True)),FramerRTU(DecodePDU(False))
    entries=[]
    for index in range(7):
        device=1 if index==0 else rng.randrange(1,248)
        address=0 if index==0 else rng.randrange(0,65534)
        registers=[0x1234,0x5678] if index==0 else [rng.randrange(65536) for _ in range(1+index%3)]
        request=req_framer.buildFrame(ReadHoldingRegistersRequest(address=address,count=len(registers),dev_id=device))
        response=resp_framer.buildFrame(ReadHoldingRegistersResponse(registers=registers,dev_id=device))
        corrupt=index==5;invalid_gap=index==6
        if corrupt:response=response[:-1]+bytes([response[-1]^1])
        entries.append({'index':index,'device':device,'address':address,'registers':registers,
                        'baud':115200 if index%2 else 19200,'npar':index==4,
                        'bad_crc':corrupt,'invalid_gap':invalid_gap,
                        'request':request.hex(),'response':response.hex()})
    assert entries[0]['request']=='010300000002c40b'
    assert entries[0]['response']=='010304123456788107'
    lines=['// Generated by pymodbus FramerRTU.buildFrame; no local CRC implementation.',
           'task automatic modbus_reference;', '  bit invalid;',
           '  $display("Independent pymodbus RTU framer pin tests");',
           "  reg_write(7'h00,8'hc0); reg_write(7'h04,0); reg_write(7'h02,3);",
           '  load_program("modbus_image.hex");',
           "  reg_write(7'h03,0); reg_write(7'h12,0); reg_write(7'h13,1);",
           "  reg_write(7'h14,0); reg_write(7'h15,0);",
           "  reg_write(7'h19,8'h05); reg_write(7'h1a,8'h80); reg_write(7'h1b,8'hff);",
           '  mb_en=1; mb_bad=-1;']
    for entry in entries:
        i=entry['index']; npar=int(entry['npar']); gap=entry['invalid_gap']
        lines += [f'  mb_baud={entry["baud"]}.0; mb_npar={npar};',
                  f"  reg_write(7'h1e,8'h{'41' if npar else '01'}); mb_config;",
                  f'  mb_gap_at={4 if gap else -1}; mb_gap_chars=2.0;',
                  f'  mb_buf={queue(bytes.fromhex(entry["request"]))};',
                  f'  mb_resp={queue(bytes.fromhex(entry["response"]))};',
                  '  mb_max_gap=0; mb_send; mb_receive;',
                  '  flag_get(0,3,invalid); flag_clear(0,3); flag_clear(0,2);',
                  "  reg_write(7'h02,3);",
                  f'  check(invalid=={int(gap)},"independent Modbus frame-gap status");',
                  '  check(mb_max_gap<=1.5*11*MB_BIT,"independent Modbus request inter-character gap");',
                  '  check(mb_req_got.size()==mb_buf.size(),"independent Modbus request length");',
                  '  foreach(mb_buf[i]) if(i<mb_req_got.size()) check(mb_req_got[i]===mb_buf[i],"independent Modbus request/CRC byte");',
                  f'  check(mb_rx.size()=={4 if gap else len(bytes.fromhex(entry["response"]))},"independent Modbus response length");',
                  '  foreach(mb_rx[i]) begin check(mb_rx[i]===mb_resp[i],"independent Modbus response byte");',
                  '    mb_x=mb_par[i]; check(!mb_x[0],"independent Modbus parity status"); end']
        if not gap:
            lines.append(f'  mb_x=mb_par[mb_par.size()-1]; check(mb_x[1]=={int(not entry["bad_crc"])},"independent Modbus CRC acceptance");')
        lines += [f'  $write("REF_MODBUS_REQUEST {i} "); foreach(mb_req_got[i]) $write("%02x",mb_req_got[i]); $display("");',
                  f'  $write("REF_MODBUS_RESPONSE {i} "); foreach(mb_rx[i]) $write("%02x",mb_rx[i]); $display("");']
    lines += ['  mb_en=0;',
              '  check(mb_par_err==0 && mb_stop_err==0 && mb_de_err==0,"independent Modbus framing/driver errors");',
              '  if(errors) $fatal(1,"independent Modbus vectors failed: %0d",errors);',
              '  $display("REFERENCE_MODBUS_PASS cases=7");','endtask']
    (output/'modbus_reference.svh').write_text('\n'.join(lines)+'\n')
    return entries


def call(command,output,cwd):
    start=time.monotonic();proc=subprocess.run([str(x) for x in command],cwd=cwd,capture_output=True)
    output.with_suffix('.stdout').write_bytes(proc.stdout);output.with_suffix('.stderr').write_bytes(proc.stderr)
    output.with_suffix('.command.json').write_text(json.dumps([str(x) for x in command],indent=2)+'\n')
    if proc.returncode:raise RuntimeError(f'{command[0]} exited {proc.returncode}; inspect {output}.stdout/stderr')
    return proc.stdout.decode(),round(time.monotonic()-start,3)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output',type=Path,default=ROOT/'build'/'reference_protocols')
    parser.add_argument('--seed',type=lambda x:int(x,0),default=0x50424532)
    parser.add_argument('--protocol',choices=['all','usb','modbus'],default='all')
    args=parser.parse_args();output=args.output.resolve();output.mkdir(parents=True,exist_ok=True)
    (output/'results.json').unlink(missing_ok=True)
    for tool in ('iverilog','vvp'):
        if not shutil.which(tool):raise RuntimeError(f'{tool} is required')
    rng=random.Random(args.seed)
    usb=usb_vectors(output,rng);modbus=modbus_vectors(output,rng)
    manifest={'seed':args.seed,'versions':{name:importlib.metadata.version(name) for name in ('usb-protocol','luna-usb','pymodbus')},
              'usb':usb,'modbus':modbus}
    (output/'vectors.json').write_text(json.dumps(manifest,indent=2)+'\n')
    call(['make','test/usb_image.hex','test/modbus_image.hex'],output/'assemble',ROOT)
    results=[]
    for protocol,bench,marker in [('usb','tb_usb','REFERENCE_USB_PASS'),('modbus','tb_pbe','REFERENCE_MODBUS_PASS')]:
        if args.protocol not in ('all',protocol):continue
        sim=output/(protocol+'.vvp')
        call(['iverilog','-g2012','-DPBE_PROTOCOL_REFERENCE','-I',output,'-s',bench,'-o',sim,
              ROOT/'test'/(bench+'.sv'),*SOURCES],output/(protocol+'_compile'),ROOT/'test')
        text,seconds=call(['vvp','-n',sim],output/(protocol+'_run'),ROOT/'test')
        if marker not in text:raise RuntimeError(f'{protocol} missing PASS marker')
        # Captured device bytes are checked again outside the SV bench by the
        # independent libraries; this compares actual DUT traffic, not an oracle
        # round trip where the same function generates both sides.
        details={}
        if protocol=='usb':
            sent=re.findall(r'REF_USB_SENT (\d+) ([0-9a-f]+)',text)
            assert sent
            for index,raw in sent:
                assert raw==usb['packets'][int(index)]['hex']
            details['host_packets']=len(sent)
            actual=re.findall(r'REF_USB_RESPONSE (\d+) ([0-9a-f]+)',text)
            assert [int(index) for index,_ in actual]==usb['expected_responses'], actual
            for index,raw in actual:
                assert raw==usb['packets'][int(index)]['hex']
            details['device_responses']=len(actual)
        else:
            from pymodbus.framer.rtu import FramerRTU
            from pymodbus.pdu import DecodePDU
            details['cases']=len(modbus)
            for mode in ('REQUEST','RESPONSE'):
                actual=re.findall(rf'REF_MODBUS_{mode} (\d+) ([0-9a-f]+)',text)
                assert len(actual)==len(modbus)
                for index,raw in actual:
                    entry=modbus[int(index)];frame=bytes.fromhex(raw)
                    framer=FramerRTU(DecodePDU(mode=='REQUEST'))
                    used,device,_,payload=framer.decode(frame)
                    reject=mode=='RESPONSE' and (entry['bad_crc'] or entry['invalid_gap'])
                    assert bool(used)==(not reject),(mode,index,raw,used)
                    if not reject:assert device==entry['device'] and payload==frame[1:-2]
        results.append({'protocol':protocol,'status':'PASS','seconds':seconds,'pass_marker':marker,**details})
        print(f'PASS {protocol}: {seconds}s',flush=True)
    manifest['results']=results
    manifest['source_sha256']={str(path.relative_to(ROOT)):hashlib.sha256(path.read_bytes()).hexdigest() for path in SOURCES}
    (output/'results.json').write_text(json.dumps(manifest,indent=2)+'\n')
    return 0


if __name__=='__main__':
    try:sys.exit(main())
    except (OSError,RuntimeError,AssertionError,ImportError) as exc:
        print(f'ERROR: {exc}',file=sys.stderr);sys.exit(1)
